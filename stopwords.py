# LANGUAGE MAPPING


stopwords_dict = {

    "telugu": telugu_stopwords,
    "malayalam": malayalam_stopwords,
    "tamil": tamil_stopwords,
    "kannada": kannada_stopwords
}

# STEMMER

stemmer = PorterStemmer()

# MAIN FUNCTION

def preprocess_text(text, language):

    language = language.lower()

    # Check supported language
    if language not in stopwords_dict:

        return {
            "error": "Language not supported"
        }

    # TOKENIZATION

    tokens = text.split()

    # STOPWORD REMOVAL

    filtered_tokens = [

        word for word in tokens
        if word not in stopwords_dict[language]
    ]

    # STEMMING

    stemmed_tokens = [

        stemmer.stem(word)
        for word in filtered_tokens
    ]

    # RETURN OUTPUT

    return {

        "tokens": tokens,

        "after_stopword_removal": filtered_tokens,

        "after_stemming": stemmed_tokens
    }